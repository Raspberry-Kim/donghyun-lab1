export function number(n){
  if(n===0)return '도옹ㅠ';
  if(n<0)return 'ㅠ '+number(-n);
  if(n<=10)return '도'+'오'.repeat(n-1)+'옹';
  for(let a=10;a>=2;a--)if(n%a===0)return number(a)+' '+number(n/a);
  return '도'+'오'.repeat(n-1)+'옹';
}
